#!/usr/bin/env python3
"""Check the axioms of every theorem restated in TlsMpc/Security.lean; write SECURITY_AXIOMS.txt.

    python3 scripts/check_axioms.py              # run Lean (heavy-job lock), check, write the file
    python3 scripts/check_axioms.py --from-log F # parse a saved `lake env lean` output instead

Runs `lake env lean TlsMpc/Security.lean` through `scripts/guarded.py` (10 GB cap). This is a light
job: it only reads existing .olean files (about 1 GB, a few seconds), so it takes no heavy-job lock;
if a concurrent build is rewriting an .olean it imports, retry a minute later. Then:
  * fails on any Lean error;
  * fails unless every `theorem` of TlsMpc.Security has exactly one `#print axioms` result;
  * fails on any axiom other than propext, Classical.choice, Quot.sound — Lean.ofReduceBool is
    allowed only for entries that the file's own check reports as depending on `bv_decide`;
  * writes SECURITY_AXIOMS.txt (checked in), so a change of axioms shows up as a diff.
The full Lean output is kept in .deps/check-axioms.log (not checked in).
"""
import os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = os.path.join(ROOT, 'TlsMpc', 'Security.lean')
OUTPUT = os.path.join(ROOT, 'SECURITY_AXIOMS.txt')
LOG = os.path.join(ROOT, '.deps', 'check-axioms.log')
ALLOWED = {'propext', 'Classical.choice', 'Quot.sound'}
BV_DECIDE_ONLY = {'Lean.ofReduceBool'}


def run_lean():
    cmd = ['python3', os.path.join(ROOT, 'scripts', 'guarded.py'), '10', '1800',
           'lake', 'env', 'lean', 'TlsMpc/Security.lean']
    r = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True)
    os.makedirs(os.path.dirname(LOG), exist_ok=True)
    with open(LOG, 'w') as f:
        f.write(r.stdout + '\n--- stderr ---\n' + r.stderr)
    return r.returncode, r.stdout


def restated_names():
    names, namespace = [], None
    for line in open(SOURCE, encoding='utf-8'):
        m = re.match(r'^namespace\s+(\S+)', line)
        if m:
            namespace = m.group(1)
        if re.match(r'^end\s+TlsMpc\.Security\b', line):
            namespace = None
        m = re.match(r'^theorem\s+(\S+)', line)
        if m and namespace == 'TlsMpc.Security':
            names.append('TlsMpc.Security.' + m.group(1))
    return names


def parse(text):
    flat = re.sub(r'\s+', ' ', text)
    axioms = {}
    for m in re.finditer(r"'([^']+)' depends on axioms: \[([^\]]*)\]", flat):
        axioms.setdefault(m.group(1), []).append(sorted(a.strip() for a in m.group(2).split(',') if a.strip()))
    for m in re.finditer(r"'([^']+)' does not depend on any axioms", flat):
        axioms.setdefault(m.group(1), []).append([])
    bv_constants = re.findall(r'bv_decide constant reached: (\S+)', text)
    bv_dependents = re.findall(r'depends on bv_decide: (\S+)', text)
    summary = re.findall(r'entries depending on bv_decide: (\d+) of (\d+)', text)
    errors = [line for line in text.splitlines() if ': error' in line]
    return axioms, bv_constants, bv_dependents, summary, errors


def main():
    if len(sys.argv) == 3 and sys.argv[1] == '--from-log':
        code, text = 0, open(sys.argv[2]).read().split('\n--- stderr ---\n')[0]
    else:
        code, text = run_lean()
    axioms, bv_constants, bv_dependents, summary, errors = parse(text)
    problems = []
    if errors:
        problems += ['Lean error: ' + e for e in errors[:20]]
    elif code != 0:
        problems.append(f'lake env lean exited with {code}')
    names = restated_names()
    bv_set = set(bv_dependents)
    for n in names:
        found = axioms.get(n, [])
        if len(found) != 1:
            problems.append(f'{n}: {len(found)} `#print axioms` results (want 1)')
            continue
        for a in found[0]:
            if a in ALLOWED or (a in BV_DECIDE_ONLY and n in bv_set):
                continue
            problems.append(f'{n}: axiom {a} not allowed')
    if not summary:
        problems.append('the bv_decide dependency check printed no summary')

    lines = ['# Axioms of every theorem restated in TlsMpc/Security.lean.',
             '# Generated by scripts/check_axioms.py (`lake env lean TlsMpc/Security.lean`); do not edit.',
             '# Allowed: propext, Classical.choice, Quot.sound; Lean.ofReduceBool only for bv_decide dependents.',
             '']
    for n in names:
        found = axioms.get(n, [[]])
        short = n[len('TlsMpc.Security.'):]
        lines.append(f'{short}: [{", ".join(found[0]) if found else ""}]')
    lines += ['', '# The five bv_decide uses (SECURITY_MAP C.6): axioms of the public theorems that contain them']
    for n in ['TlsMpc.TlsWebSocketActivity.activity_valid', 'TlsMpc.TlsPrivateSeal.build_correct',
              'TlsMpc.TlsPrivateSeal.seal_status']:
        found = axioms.get(n, [])
        lines.append(f'{n}: [{", ".join(found[0])}]' if found else f'{n}: MISSING')
        if not found:
            problems.append(f'{n}: no `#print axioms` result')
    lines += ['', '# bv_decide constants reached from the restated theorems']
    lines += [f'reached: {c}' for c in sorted(set(bv_constants))] or ['reached: none']
    lines += ['', '# Restated theorems that depend (transitively) on a bv_decide proof']
    lines += [f'depends: {d[len("TlsMpc.Security."):]}' for d in sorted(bv_set)] or ['depends: none']
    if summary:
        lines.append(f'# {summary[-1][0]} of {summary[-1][1]} entries')
    with open(OUTPUT, 'w') as f:
        f.write('\n'.join(lines) + '\n')

    print(f'{len(names)} restated theorems; {len(bv_set)} depend on bv_decide; wrote {os.path.relpath(OUTPUT, ROOT)}')
    if problems:
        print('FAILED:')
        for p in problems:
            print('  ' + p)
        sys.exit(1)
    print('OK: only allowed axioms')


if __name__ == '__main__':
    main()
