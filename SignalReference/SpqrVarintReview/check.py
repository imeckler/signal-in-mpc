HERE = Path(__file__).resolve().parent
REFERENCE = HERE.parent
ROOT = REFERENCE.parent
WORK = REFERENCE / 'SpqrReference'


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def walk(value, path=()):
    yield path, value
    if isinstance(value, dict):
        for key, item in value.items():
            yield from walk(item, (*path, key))
    elif isinstance(value, list):
        for key, item in enumerate(value):
            yield from walk(item, (*path, key))


def main():
    pins = {
        WORK / 'Artifacts/varint/spqr.llbc': '4ca6cf0b654e390018974569b0ed956687aa4a52206cf7354fa2ada91f2829ab',
        WORK / 'VarintSelected/selected.llbc': 'ccc7721bf9a4bc1395ecfc758b52618471b47adda63ff3991141c0e84439fd4a',
        WORK / 'VarintSelected/changes.json': '0d5b8257a6b8f03558429c5f35993638a4c25e5e1753eec91ef04ec5bc9a08b7',
        WORK / 'select_varint.py': 'b7c561eeb0de0bd273762f40e7e1f87572632eced1c0ae0ae8ce47202a7f6bd8',
        WORK / 'proof-report.json': '36123b2a0361ae3aeb5ba07b6d25d3d150ee64137ca05fb004c7c6469dc81e6b',
        ROOT / '.deps/aeneas-2026-08-27/aeneas': '323e2e1ce117cccf866c9e1fb9925671ec25312006f6d51da72ef95638612ed7',
        ROOT / '.deps/spqr-06959b4.tar.gz': 'f8fd4b1356a678fa49bbf4c51801c38d3b53ea800178579bef9ff47321b2058f',
        REFERENCE / 'ProstEncodingWork/AdvanceWork/TranslatorCandidate/aeneas-5b9dcf33.tar.gz':
            'ceb3a9a8114488f7deef705599316d1282133b4aea203cbf902117c11175d453',
    }
    for path, expected in pins.items():
        assert digest(path) == expected, path
    before = json.loads((WORK / 'Artifacts/varint/spqr.llbc').read_text())
    after = json.loads((WORK / 'VarintSelected/selected.llbc').read_text())
    changes = json.loads((WORK / 'VarintSelected/changes.json').read_text())
    expected_paths = [
        ['translated', 'trait_decls', 1, 'methods', 2],
        ['translated', 'trait_impls', 2, 'methods', 2],
        ['translated', 'fun_decls', 96],
        ['translated', 'trait_decls', 1, 'methods', 6],
        ['translated', 'trait_impls', 2, 'methods', 6],
        ['translated', 'fun_decls', 100],
        ['translated', 'ordered_decls'],
    ]
    assert [c['path'] for c in changes] == expected_paths
    assert all(c['after'] is None for c in changes[:-1])
    replay = copy.deepcopy(before)
    for change in changes:
        current = replay
        for item in change['path'][:-1]:
            current = current[item]
        assert current[change['path'][-1]] == change['before']
        current[change['path'][-1]] = change['after']
    assert replay == after
    restored = copy.deepcopy(after)
    for change in reversed(changes):
        current = restored
        for item in change['path'][:-1]:
            current = current[item]
        assert current[change['path'][-1]] == change['after']
        current[change['path'][-1]] = change['before']
    assert restored == before
    b, a = before['translated'], after['translated']
    assert a['ordered_decls'] == [x for x in b['ordered_decls']
                                  if x not in [{'Fun': {'NonRec': 96}}, {'Fun': {'NonRec': 100}}]]
    computational = [i for i, f in enumerate(b['fun_decls']) if f and f['body'] != 'Opaque']
    assert computational == [0, 4]
    for i in computational:
        assert b['fun_decls'][i] == a['fun_decls'][i]
    for slot, index, name in ((2, 96, 'forward_overflowing'), (6, 100, 'backward_overflowing')):
        assert b['trait_decls'][1]['methods'][slot]['skip_binder']['name'] == name
        assert b['trait_impls'][2]['methods'][slot]['skip_binder']['id'] == index
        assert b['fun_decls'][index]['body'] == 'Opaque' and a['fun_decls'][index] is None
    # Exhaustive replay above establishes the ONLY differences. This separate
    # scan checks all signatures, globals, dictionaries and bodies for stale
    # typed references to the two removed, uncalled Step entries.
    nodes, direct_calls = 0, set()
    for key in ('type_decls', 'fun_decls', 'global_decls', 'trait_decls', 'trait_impls'):
        for path, node in walk(a[key], (key,)):
            nodes += 1
            if not isinstance(node, dict):
                continue
            regular = node.get('Regular')
            if isinstance(regular, int):
                assert regular not in (96, 100), path
            trait_method = node.get('TraitMethod')
            if isinstance(trait_method, list):
                assert trait_method not in [[1, 2], [1, 6]], path
            trait_call = node.get('Trait')
            if isinstance(trait_call, list) and len(trait_call) == 2:
                ref = trait_call[0].get('Untagged', {}).get('trait_decl_ref', {}).get('skip_binder', {})
                assert (ref.get('id'), trait_call[1]) not in ((1, 2), (1, 6)), path
            default = node.get('default')
            assert not isinstance(default, dict) or default.get('id') not in (96, 100), path
    for index in computational:
        for _, node in walk(a['fun_decls'][index]['body']):
            if isinstance(node, dict) and isinstance(node.get('Regular'), int):
                direct_calls.add(node['Regular'])
    assert direct_calls == {1, 2, 3}, direct_calls
    # The actual calls are official IntoIterator/Range.next/Vec.push models.
    selection = json.loads((WORK / 'VarintSelected/review.json').read_text())
    assert selection['aeneas_exit_code'] == 0 and selection['remaining_external_templates'] == []
    for filename, expected in selection['generated_files'].items():
        assert digest(REFERENCE / filename) == expected
    inventory = json.loads((WORK / 'Artifacts/varint/inventory.json').read_text())
    assert inventory['charon_exit_code'] == 0 and not inventory['has_errors']
    assert inventory['source_patches'] == [] and not inventory['hax_cfg_enabled']
    for filename, expected in inventory['source_sha256'].items():
        assert digest(ROOT / filename) == expected
    upstream = ROOT / '.deps/libsignal-vendor/spqr'
    compared = set()
    with tarfile.open(ROOT / '.deps/spqr-06959b4.tar.gz') as archive:
        for member in archive.getmembers():
            if member.isfile():
                prefix, name = member.name.split('/', 1)
                assert prefix == 'SparsePostQuantumRatchet-06959b4708f9b7b1e94d0f8cc835f3958c077e94'
                path = upstream / name
                assert path.read_bytes() == archive.extractfile(member).read(), name
                compared.add(path)
    assert len(compared) == 99
    assert {p for p in upstream.rglob('*') if p.is_file()} - compared == {upstream / '.cargo-checksum.json'}
    assert b['fun_decls'][0]['item_meta']['source_text'] in (upstream / 'src/lib.rs').read_text()
    official = ROOT / '.deps/aeneas-2026-08-27'
    models = sorted((official / 'backends/lean/Aeneas/Std').rglob('*.lean'))
    with tarfile.open(REFERENCE / 'ProstEncodingWork/AdvanceWork/TranslatorCandidate/aeneas-5b9dcf33.tar.gz') as archive:
        members = {m.name.split('/', 1)[1]: m for m in archive.getmembers() if m.isfile() and '/' in m.name}
        for path in models:
            assert path.read_bytes() == archive.extractfile(members[str(path.relative_to(official))]).read(), path
    assert len(models) == 87
    iterator = (official / 'backends/lean/Aeneas/Std/Core/Iter.lean').read_text()
    assert 'forward_overflowing' not in iterator and 'backward_overflowing' not in iterator
    report = json.loads((WORK / 'proof-report.json').read_text())
    for filename, expected in report['source_sha256'].items():
        assert digest(ROOT / filename) == expected, filename
    cache = Path('/Users/izzy/repos/eco-theorem-combined/.lake/packages')
    paths = [REFERENCE / '.lake/build/lib/lean', ROOT / '.lake/build/lib/lean',
             official / 'backends/lean/.lake/build/lib/lean']
    paths += sorted(p / '.lake/build/lib/lean' for p in cache.iterdir() if (p / '.lake/build/lib/lean').is_dir())
    env = os.environ.copy()
    env['LEAN_PATH'] = os.pathsep.join(str(p) for p in paths)
    checked = subprocess.run(['lean', 'SpqrReference/Checks.lean'], cwd=REFERENCE, env=env,
                             capture_output=True, text=True, check=True)
    expected = re.findall(r'^#print axioms (\S+)', (WORK / 'Checks.lean').read_text(), re.M)
    found = re.findall(r"'([^']+)' (?:depends on axioms: \[([^]]*)\]|does not depend on any axioms)", checked.stdout)
    allowed = {'propext', 'Classical.choice', 'Quot.sound'}
    assert [name for name, _ in found] == expected and len(found) == 21
    for name, axioms in found:
        assert not ({x.strip() for x in axioms.split(',') if x.strip()} - allowed), name
    for filename, expected in report['source_sha256'].items():
        assert digest(ROOT / filename) == expected, filename
    files = [*pins, WORK / 'VarintSelected/review.json', WORK / 'Artifacts/varint/inventory.json',
             WORK / 'Checks.lean', Path(__file__)]
    result = {'independent_review': True, 'reviewer': '/root/signal_lean_aeneas',
              'author': '/root/signal_lean_aeneas/pkcs7_reference', 'checks_passed': True,
              'accepted_scope': 'Actual SPQR encode_varint through official Range/StepUsize/Vec.push models and its uint64/uint32 circuit bridges.',
              'exact_reversible_changes': len(changes), 'unchanged_computational_declarations': computational,
              'direct_computational_calls': sorted(direct_calls), 'semantic_nodes_scanned': nodes,
              'all_upstream_spqr_files_compared': len(compared), 'all_standard_model_files_compared': len(models),
              'fresh_kernel_axiom_endpoints': len(found), 'allowed_foundational_axioms': sorted(allowed),
              'unconditional_errors_retained': 'encode_eq_run preserves every Vec.push Result; concrete append/artifact endpoints state buffer.length+10<=Usize.max.',
              'additional_trusted_preprocessing': True, 'mechanized_selection_correctness': False,
              'custom_crypto_buffer_or_standard_models': [], 'rust_source_changes': [],
              'full_spqr_serializer_or_state_equivalence': False,
              'source_sha256': {str(p.relative_to(ROOT)): digest(p) for p in files},
              'generated_files': selection['generated_files']}
    (HERE / 'review.json').write_text(json.dumps(result, indent=2) + '\n')
    print('Independent SPQR review passed: 7 metadata edits, 2 actual bodies unchanged, 21 standard-axiom endpoints.')


if __name__ == '__main__':
    main()
