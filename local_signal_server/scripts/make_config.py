#!/usr/bin/env python3
"""Write state/server/local.yml: Signal-Server's own test configuration
(service/src/test/resources/config/test.yml) with ONLY network bindings changed:

  application connector  h2c 8080 (all interfaces)  ->  h2c 127.0.0.1:18080
  admin connector        default 8081               ->  127.0.0.1:18081
  gRPC omnibus           50051 / websocketPort 8080 ->  18051 / 18080
  S3 (PQ prekey pages, CDN) real AWS us-west-2      ->  http://127.0.0.1:1 (closed; fails locally)

Everything else (embedded DynamoDB/Redis via Testcontainers, stub registration
service, unidentified-delivery certificate and the documented test trust root)
is upstream test configuration, unchanged. The secrets come from the upstream
test-secrets-bundle.yml, which LocalWhisperServerService loads itself.

Usage: make_config.py SIGNAL_SERVER_SRC OUTPUT_YML
"""
import sys
from pathlib import Path

src, out = Path(sys.argv[1]), Path(sys.argv[2])
text = (src / 'service/src/test/resources/config/test.yml').read_text()

REPLACEMENTS = [
    # One-time PQ prekey pages and CDN attachments live in S3. Upstream test.yml would send those
    # requests to real AWS (us-west-2) with dummy credentials. Point both S3 clients at a closed
    # loopback port so any such request fails locally and nothing leaves the machine. (LocalStack
    # cannot stand in: it rejects the upstream bucket name `preKeyBucket`, and a lowercase name
    # would make the AWS SDK use virtual-host addressing.) Consequence: clients must not upload
    # one-time PQ prekeys (`pqPreKeys`); bundles then carry the signed last-resort PQ key.
    ('pagedSingleUseKEMPreKeyStore:\n  bucket: preKeyBucket # S3 Bucket name\n  region: us-west-2    # AWS region\n',
     'pagedSingleUseKEMPreKeyStore:\n  bucket: preKeyBucket # S3 Bucket name\n  region: us-west-2    # AWS region\n'
     '  endpointOverride: http://127.0.0.1:1\n'),
    ('  region: us-west-2  # AWS region\n\ncdn3StorageManager:',
     '  region: us-west-2  # AWS region\n  endpointOverride: http://127.0.0.1:1\n\ncdn3StorageManager:'),
    ('grpc:\n  port: 50051\n  websocketPort: 8080\n',
     'grpc:\n  bindAddress: 127.0.0.1\n  port: 18051\n  websocketPort: 18080\n'),
    ('  applicationConnectors:\n    - type: h2c\n      port: 8080\n      useForwardedHeaders: true\n',
     '  applicationConnectors:\n    - type: h2c\n      bindHost: 127.0.0.1\n      port: 18080\n      useForwardedHeaders: true\n'
     '  adminConnectors:\n    - type: http\n      bindHost: 127.0.0.1\n      port: 18081\n'),
]
for old, new in REPLACEMENTS:
    if text.count(old) != 1:
        raise SystemExit('test.yml layout changed; update make_config.py for: ' + old.splitlines()[0])
    text = text.replace(old, new)

out.parent.mkdir(parents=True, exist_ok=True)
out.write_text('# GENERATED by local_signal_server/scripts/make_config.py from upstream test.yml; do not edit.\n' + text)
print(out)
